// Builds episode.html in exactly the same shape as the hand-made episodes.
const js = v => JSON.stringify(v);
const num = v => String(Math.round(v * 100) / 100);

function subtitle(length) {
  const m = Math.floor(length / 60), s = Math.round(length % 60);
  const mins = m === 0 ? '' : m === 1 ? 'دقيقة' : m === 2 ? 'دقيقتان' : `${m} دقائق`;
  const secs = s ? `${s} ثانية` : '';
  return 'حلقة بصوت الراوي، ' + [mins, secs].filter(Boolean).join(' و');
}

function assemble({ title, length, poster, captions, chapters, helpers, model }) {
  const at = chapters.map(c => `${c.key}:${num(c.at)}`).join(', ');
  const caps = captions.map(c => `[${num(c[0])},${js(c[1])}]`);
  const capLines = [];
  for (let i = 0; i < caps.length; i += 4) capLines.push('    ' + caps.slice(i, i + 4).join(','));
  const chs = chapters.map((c, i) => `  // ===== ${i + 1}. ${String(c.idea || c.key).replace(/\*\//g, '')} (${num(c.at)} – ${num(c.end)}) =====\n` +
    `  {at:AT.${c.key}, build:SAFE(${js(c.key)}, ${c.code.trim()})}`).join(',\n\n');
  return `<title>${String(title).replace(/[<&]/g, '')}</title>
<div id="app"></div>
<script src="https://cdnjs.cloudflare.com/ajax/libs/gsap/3.12.5/gsap.min.js"></script>
<script src="story-engine.js"></script>
<script>
/* Generated by Tasaalt Studio with DeepSeek${model ? ' (' + model + ')' : ''}. Timed to voice.mp3 (${num(length)} s).
   L(t) converts absolute seconds to chapter time. Scene words stay above y≈520 (caption band in the exported video). */
(function(){
var AT={${at}};

function sub(S,g,bg){ var s=S('g',{opacity:0},g); if(bg) S('rect',{x:0,y:0,width:360,height:640,fill:bg},s); return s; }
function cut(tl,from,to,at){ if(from) tl.to(from,{opacity:0,duration:0.3},at); tl.to(to,{opacity:1,duration:0.3},at); }
// A chapter that throws never breaks the whole episode; the error is reported to the studio.
function SAFE(key,fn){ return function(g,tl,K){ try{ fn(g,tl,K); }catch(e){ (window.__genErr=window.__genErr||{})[key]=String(e&&e.message||e); } }; }

${(helpers || '').trim()}

Story.episode({
  title:${js(title)},
  sub:${js(subtitle(length))},
  audio:'voice.mp3',
  length:${num(length)},
  poster:${num(poster)},
  captions:[
${capLines.join(',\n')}
  ],
  chapters:[

${chs}
  ]
});
})();
</script>
`;
}

// Safe template chapter used only when the AI version keeps failing: background + kinetic words on their beats.
const BGS = [['#0f1a33', false], ['#f6d8a8', true], ['#1d1a2e', false], ['#a8d5e2', true], ['#2b2f4a', false], ['#f4e9d8', true], ['#070b1c', false]];
function fallbackChapter(ch, index) {
  const [bg, light] = BGS[index % BGS.length];
  const ink = light ? '#2a2a30' : '#ffffff', stroke = light ? ",{stroke:'#f4e9d8'}" : '';
  const cues = (ch.cues || []).filter(c => c.text).slice(0, 6);
  let code = `function(g,tl,K){
    var S=K.S, T=K.T, L=function(t){return t-AT.${ch.key};};
    var a=sub(S,g,${js(bg)});
    S('path',{d:'M0 440 Q180 410 360 440 V640 H0Z',fill:${js(light ? '#c9b48a' : '#1d2b48')}},a);
    for(var i=0;i<24;i++) S('circle',{cx:K.rr(0,360),cy:K.rr(0,420),r:K.rr(1,3),fill:${js(light ? '#ffffff' : '#9fd8ff')},opacity:K.rr(0.2,0.6)},a);
    var glow=S('circle',{cx:180,cy:330,r:110,fill:'#ffd166',opacity:0.12},a);
    tl.to(glow,{scale:1.15,svgOrigin:'180 330',duration:1.2,yoyo:true,repeat:${Math.max(1, Math.ceil((ch.end - ch.at) / 1.2))},ease:'sine.inOut'},0);
    cut(tl,null,a,0);\n`;
  cues.forEach((c, i) => {
    const txt = String(c.text);
    const size = Math.max(20, Math.min(c.role === 'hero' || c.role === 'number' ? 48 : 26, Math.floor(300 / (0.55 * Math.max(1, txt.length)))));
    const color = c.role === 'hero' ? '#e4572e' : c.role === 'number' ? '#ffd166' : ink;
    const y = i % 2 === 0 ? 130 : 330;
    code += `    var w${i}=T(g,${js(txt)},180,${y},${size},${js(color)}${stroke});\n`;
    code += `    K.${c.role === 'hero' || c.role === 'number' ? 'slam' : 'slide'}(tl,w${i},L(${num(c.t)}));\n`;
    const next = cues[i + 2];
    if (next) code += `    K.hide(tl,w${i},L(${num(Math.max(c.t + 0.5, next.t - 0.1))}));\n`;
  });
  code += '  }';
  return code;
}

module.exports = { assemble, fallbackChapter, subtitle };
